file = open("seek_example.txt", "w+")
file.write("Python File Handling Example")
file.flush()
print("Current position after write:", file.tell())
file.seek(0)
print("Position after seek(0):", file.tell())
print("Reading from beginning:", file.read(8))
file.seek(9)
print("Position after seek(6):", file.tell())
print("Reading from position 6:", file.read(5))
file.close()
